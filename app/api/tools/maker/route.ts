export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const type = String(body?.type || "").toLowerCase();
    const text = String(body?.text || "").trim();

    if (!text) {
      return NextResponse.json({ ok: false, error: "Teks wajib diisi." }, { status: 400 });
    }

    let svg = "";
    if (type === "iqc") {
      const provider = String(body?.provider || "MattzLM").slice(0, 20);
      const time = String(body?.time || "12:00").slice(0, 10);
      const battery = String(body?.battery || "85").replace(/[^0-9]/g, "").slice(0, 3) || "85";
      svg = buildIqcSvg(text, provider, time, battery);
    } else if (type === "tanyaustadz") {
      const answer =
        String(body?.answer || "").trim() ||
        "Sabar dan perbanyak istighfar, semua proses butuh usaha dan doa.";
      svg = buildTanyaUstadzSvg(text, answer);
    } else if (type === "sertifikat") {
      const award =
        String(body?.award || "").trim() ||
        "Atas kontribusi aktif di MattzLM";
      const issuer = String(body?.issuer || "MattzLM Official").trim().slice(0, 28);
      svg = buildSertifikatSvg(text, award, issuer);
    } else {
      return NextResponse.json({ ok: false, error: "Tipe maker tidak dikenali." }, { status: 400 });
    }

    const png = await sharp(Buffer.from(svg)).png({ compressionLevel: 8 }).toBuffer();
    return new NextResponse(new Uint8Array(png), {
      status: 200,
      headers: {
        "Content-Type": "image/png",
        "Cache-Control": "no-store",
      },
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Gagal membuat gambar di VPS.";
    return NextResponse.json({ ok: false, error: msg }, { status: 500 });
  }
}
